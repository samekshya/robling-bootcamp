USE DATABASE SNOWFLAKE_LEARNING_DB;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

-- E1. Reconciliation: every check PASS for all 5 days (11 checks x 5 days)
SELECT BUSINESS_DATE, CHECK_NM, SOURCE_VALUE, TARGET_VALUE, DIFFERENCE, STATUS_CD
FROM SILVER.AUD_RECONCILIATION
ORDER BY BUSINESS_DATE, CHECK_NM;

-- E2. Gold net sales per day ties to the files (488/552/483/501/519 rows)
SELECT d.FULL_DT, COUNT(*) AS SALES_ROWS, SUM(f.SLS_AMT) AS NET_SALES
FROM RETAIL_DW.FCT_SALES f
JOIN RETAIL_DW.DIM_DAY d ON d.DAY_KY = f.DAY_KY
GROUP BY d.FULL_DT ORDER BY d.FULL_DT;

-- E3. Day 3 quarantine: 5 rows, run did not stop
SELECT BUSINESS_DATE, SOURCE_TABLE, GATE_CD, REASON_CD, ROW_NUM, RAW_RECORD
FROM SILVER.REJ_ROW
ORDER BY BUSINESS_DATE, ROW_NUM;

-- E4. SCD2 item: 10000020 has two versions (Tees until 3 Nov, Polos from 4 Nov)
SELECT i.ITEM_KY, i.ITEM_ID, i.ITEM_NM, s.SUBCATG_NM, i.EFF_START_DT, i.EFF_END_DT, i.CURR_FLG
FROM RETAIL_DW.DIM_ITEM i JOIN RETAIL_DW.DIM_SUBCATG s ON s.SUBCATG_KY = i.SUBCATG_KY
WHERE i.ITEM_ID IN (10000020, 10000901) ORDER BY i.ITEM_ID, i.EFF_START_DT;

-- E5. SCD2 store: 1112 has two versions (district 104 until 2 Nov, 108 from 3 Nov)
SELECT l.LOCN_KY, l.LOCN_ID, l.LOCN_NM, d.DISTRICT_ID, d.DISTRICT_NM, l.EFF_START_DT, l.EFF_END_DT, l.CURR_FLG
FROM RETAIL_DW.DIM_LOCN l JOIN RETAIL_DW.DIM_DISTRICT d ON d.DISTRICT_KY = l.DISTRICT_KY
WHERE l.LOCN_ID = 1112 ORDER BY l.EFF_START_DT;

-- E6. SCD1: item 10000722 name corrected in place (one row, UPDATE_TS later than INSERT_TS)
SELECT ITEM_KY, ITEM_ID, ITEM_NM, EFF_START_DT, CURR_FLG, INSERT_TS, UPDATE_TS
FROM RETAIL_DW.DIM_ITEM WHERE ITEM_ID = 10000722;

-- E7. Inventory: rows closed, not deleted (closed vs open rows per start date)
SELECT EFF_START_DT,
       COUNT_IF(EFF_END_DT = DATE '9999-12-31') AS OPEN_ROWS,
       COUNT_IF(EFF_END_DT < DATE '9999-12-31') AS CLOSED_ROWS
FROM RETAIL_DW.FCT_INVENTORY GROUP BY EFF_START_DT ORDER BY EFF_START_DT;

-- E8. Idempotency: run before AND after re-running the backfill; numbers must match
SELECT 'BRZ_POS_SALES' AS TBL, COUNT(*) AS ROW_CNT FROM BRONZE.BRZ_POS_SALES
UNION ALL SELECT 'SLV_SALES_LINE', COUNT(*) FROM SILVER.SLV_SALES_LINE
UNION ALL SELECT 'REJ_ROW', COUNT(*) FROM SILVER.REJ_ROW
UNION ALL SELECT 'DIM_ITEM', COUNT(*) FROM RETAIL_DW.DIM_ITEM
UNION ALL SELECT 'DIM_LOCN', COUNT(*) FROM RETAIL_DW.DIM_LOCN
UNION ALL SELECT 'DIM_DAY', COUNT(*) FROM RETAIL_DW.DIM_DAY
UNION ALL SELECT 'FCT_SALES', COUNT(*) FROM RETAIL_DW.FCT_SALES
UNION ALL SELECT 'FCT_SALES net', SUM(SLS_AMT) FROM RETAIL_DW.FCT_SALES
UNION ALL SELECT 'FCT_INVENTORY', COUNT(*) FROM RETAIL_DW.FCT_INVENTORY
UNION ALL SELECT 'FCT_INVENTORY on hand', SUM(ONHAND_QTY) FROM RETAIL_DW.FCT_INVENTORY
ORDER BY TBL;
