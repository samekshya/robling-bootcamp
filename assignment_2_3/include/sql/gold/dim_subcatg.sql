-- =====================================================================
-- Gold: SILVER.SLV_ITEM (subclass) -> RETAIL_DW.DIM_SUBCATG
-- Parent key CATG_KY is looked up from DIM_CATG by the department id.
-- SCD1 with the same IS_LATEST guard as DIM_CATG. Safe to rerun.
-- =====================================================================
MERGE INTO RETAIL_DW.DIM_SUBCATG t
USING (
    SELECT src.SUBCATG_ID, src.SUBCATG_NM, c.CATG_KY, g.IS_LATEST
    FROM (
        SELECT SUBCLASS_ID AS SUBCATG_ID, SUBCLASS_NAME AS SUBCATG_NM, DEPT_ID
        FROM SILVER.SLV_ITEM
        WHERE BUSINESS_DATE = TO_DATE('{{ ds }}')
        QUALIFY ROW_NUMBER() OVER (PARTITION BY SUBCLASS_ID ORDER BY SUBCLASS_NAME) = 1
    ) src
    JOIN RETAIL_DW.DIM_CATG c ON c.CATG_ID = src.DEPT_ID
    CROSS JOIN (
        SELECT TO_DATE('{{ ds }}') >= COALESCE(MAX(BUSINESS_DATE), TO_DATE('1900-01-01')) AS IS_LATEST
        FROM SILVER.AUD_RECONCILIATION
    ) g
) s
   ON t.SUBCATG_ID = s.SUBCATG_ID
WHEN MATCHED AND s.IS_LATEST AND (t.SUBCATG_NM <> s.SUBCATG_NM OR t.CATG_KY <> s.CATG_KY) THEN
    UPDATE SET SUBCATG_NM = s.SUBCATG_NM, CATG_KY = s.CATG_KY, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (SUBCATG_ID, SUBCATG_NM, CATG_KY) VALUES (s.SUBCATG_ID, s.SUBCATG_NM, s.CATG_KY);

SELECT COUNT(*) AS ROWS_OK, 0 AS ROWS_REJECTED FROM RETAIL_DW.DIM_SUBCATG;
