-- =====================================================================
-- Gold: SILVER.SLV_STORE (district) -> RETAIL_DW.DIM_DISTRICT
-- REGN_KY from DIM_REGN. SCD1 MERGE with the IS_LATEST guard. Safe to rerun.
-- =====================================================================
MERGE INTO RETAIL_DW.DIM_DISTRICT t
USING (
    SELECT src.DISTRICT_ID, src.DISTRICT_NM, r.REGN_KY, g.IS_LATEST
    FROM (
        SELECT DISTRICT_ID, DISTRICT_NAME AS DISTRICT_NM, REGION_ID
        FROM SILVER.SLV_STORE
        WHERE BUSINESS_DATE = TO_DATE('{{ ds }}')
        QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT_ID ORDER BY DISTRICT_NAME, STORE_ID) = 1
    ) src
    JOIN RETAIL_DW.DIM_REGN r ON r.REGN_ID = src.REGION_ID
    CROSS JOIN (
        SELECT TO_DATE('{{ ds }}') >= COALESCE(MAX(BUSINESS_DATE), TO_DATE('1900-01-01')) AS IS_LATEST
        FROM SILVER.AUD_RECONCILIATION
    ) g
) s
   ON t.DISTRICT_ID = s.DISTRICT_ID
WHEN MATCHED AND s.IS_LATEST AND (t.DISTRICT_NM <> s.DISTRICT_NM OR t.REGN_KY <> s.REGN_KY) THEN
    UPDATE SET DISTRICT_NM = s.DISTRICT_NM, REGN_KY = s.REGN_KY, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (DISTRICT_ID, DISTRICT_NM, REGN_KY) VALUES (s.DISTRICT_ID, s.DISTRICT_NM, s.REGN_KY);

SELECT COUNT(*) AS ROWS_OK, 0 AS ROWS_REJECTED FROM RETAIL_DW.DIM_DISTRICT;
